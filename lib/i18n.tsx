const LanguageContext = createContext<{
  language: Language;
  setLanguage: (language: Language) => void;
  t: (value: string) => string;
} | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>('pt-BR');

  useEffect(() => {
    const saved = window.localStorage.getItem('capimaso-language');
    if (saved === 'en' || saved === 'pt-BR') setLanguageState(saved);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language === 'pt-BR' ? 'pt-BR' : 'en';
    window.localStorage.setItem('capimaso-language', language);
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage: (next: Language) => setLanguageState(next),
    t: (value: string) => language === 'pt-BR' ? (ptBR[value] ?? value) : value
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider');
  return context;
}
